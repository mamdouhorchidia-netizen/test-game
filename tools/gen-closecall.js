const Sim = require('../closecall/src/main/assets/sim.js');

let seed = 2099;
function rnd() {
  seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const ri = (a, b) => a + Math.floor(rnd() * (b - a + 1));

function candidate(s) {
  const n = s.rows * Sim.COLS, fix = {};
  for (const k in s.fix) for (let i = 0; i < s.fix[k]; i++) {
    for (let tries = 0; tries < 50; tries++) {
      const tile = ri(2, n - 2);
      if (fix[tile]) continue;
      fix[tile] = k === 'C' ? 'C' + ri(2, 4) : k;
      break;
    }
  }
  return { rows: s.rows, hp: s.hp || ri(3, 5), fix, inv: s.inv };
}

function pick(s, idx) {
  let best = null;
  for (let n = 0; n < s.tries; n++) {
    const lv = candidate(s);
    if (Sim.run(lv, {}, false).result === 'close') continue;       // must need the director
    const a = Sim.analyze(lv);
    if (!a.wins) continue;
    const ratio = a.wins / a.total;
    if (ratio > s.max) continue;
    if (s.feature) {                                                // the new toy must matter
      const kinds = Sim.run(lv, a.sol, true).events.map(e => e.k);
      if (!s.feature.some(f => kinds.includes(f))) continue;
    }
    if (a.best < (s.minBest || 0)) continue;
    const score = Math.abs(Math.log(ratio / (s.max / 2.5))) - a.best * 0.02;
    if (!best || score < best.score) best = { lv, a, score, ratio };
  }
  if (!best) throw new Error('no scene for #' + (idx + 1));
  const { lv, a } = best;
  lv.best = a.best; lv.t2 = Math.ceil((a.min + a.best) / 2); lv.sol = a.sol;
  console.log(`scene ${idx + 1}: ${a.wins}/${a.total} set-ups work (${(best.ratio * 100).toFixed(1)}%), thrill ${a.min}..${a.best}`);
  return lv;
}

